import type { Context } from '@deepseek-ai/cordis'
import type { PreToolDecision } from '@deepseek-ai/dsh-tools'
import { absolutePath, filePathOf, isWithin, realWithin, relativePath, sessionCwd } from '../../shared/guard.ts'

export const name = 'dsh-game-studio/guard-writes'

/** The file tools whose `file_path` argument this guard inspects. */
const FILE_TOOLS: ReadonlySet<string> = new Set(['write', 'edit'])

/** The studio's own configuration folders, which a maintenance ticket may edit. */
const STUDIO_CONFIG = ['.dsh/rules/', '.dsh/skills/', '.dsh/agents/']

/**
 * Absolute filesystem paths that must never land in a committed file: a drive
 * letter, a UNC share, or a POSIX home/temp path. Evidence logs are produced by
 * commands, not by this tool, so this only constrains authored text.
 */
const ABSOLUTE_PATHS: readonly RegExp[] = [
  /(^|[^\w])([A-Za-z]:[\\/])/,
  /^\\\\[A-Za-z0-9._-]+\\/m,
  /(^|[\s"'\`(])\/(home|Users|root|tmp|mnt|var\/folders)\//,
]

/** The text a file tool is about to write, when it has one. */
function contentOf(execution: { name?: string; arguments?: unknown }): string | undefined {
  const args = execution.arguments as { content?: unknown; new_string?: unknown } | undefined
  const value = execution.name === 'edit' ? args?.new_string : args?.content
  return typeof value === 'string' ? value : undefined
}

/** The first absolute path in the text, or undefined. */
export function absolutePathIn(text: string): string | undefined {
  for (const pattern of ABSOLUTE_PATHS) {
    const match = pattern.exec(text)
    if (match) return match[0].trim().slice(0, 120)
  }
  return undefined
}

/**
 * The reason a write to `filePath` is refused, or undefined when it is allowed.
 *
 * Every refusal names the target path and says what to do instead, because the
 * reason is the only text the model sees for a denied call.
 *
 * @param cwd - the session working directory; writes must stay inside it.
 * @param filePath - the tool's `file_path`, absolute or relative to `cwd`.
 * @returns an English one-line reason, or undefined when the write is fine.
 */
export function denyReason(cwd: string, filePath: string): string | undefined {
  const target = absolutePath(cwd, filePath)
  if (!isWithin(cwd, target) || !realWithin(cwd, target)) {
    return `Refusing to write ${target}: it is outside the project directory ${cwd}. Stay inside the game repository.`
  }
  const relative = relativePath(cwd, target)
  const normalized = relative.toLowerCase()
  if (normalized === '.godot' || normalized.startsWith('.godot/')) {
    return `Refusing to write ${target}: .godot/ is Godot's generated project cache. Edit the source scene, script or resource instead.`
  }
  if (normalized.endsWith('.import')) {
    return `Refusing to write ${target}: .import files are generated by Godot's importer. Edit the asset itself and let the editor regenerate the import metadata.`
  }
  if (normalized === 'export_presets.cfg') {
    return `Refusing to write ${target}: export_presets.cfg is managed by the Godot editor. Change export presets through the editor instead of writing the file directly.`
  }
  if (normalized === '.git' || normalized.startsWith('.git/')) {
    return `Refusing to write ${target}: .git/ holds repository metadata. Use git commands instead of writing into it.`
  }
  // The studio's own configuration is edited only through its named folders;
  // a scratch script beside them is not studio configuration.
  if (normalized === '.dsh' || (normalized.startsWith('.dsh/') && !STUDIO_CONFIG.some(prefix => normalized.startsWith(prefix)))) {
    return `Refusing to write ${target}: .dsh/ holds studio configuration. Edit ${STUDIO_CONFIG.map(prefix => prefix.slice(0, -1)).join(', ')} only, and keep scratch scripts in the ticket directory, not in the repository.`
  }
  return undefined
}

/**
 * Mount the writes guard: refuse `write`/`edit` calls that target paths outside
 * the session directory or inside Godot's or git's generated trees. Every other
 * tool call delegates untouched, and an allowed write loses nothing.
 */
export function apply(ctx: Context): void {
  ctx.on('tools/pre-execute', async (exec, next): Promise<PreToolDecision> => {
    if (!FILE_TOOLS.has(exec.name)) return next()
    const filePath = filePathOf(exec)
    if (filePath === undefined) return next()
    const reason = denyReason(sessionCwd(exec.agent), filePath)
    if (reason !== undefined) return { kind: 'deny', reason }
    const content = contentOf(exec)
    const absolute = content === undefined ? undefined : absolutePathIn(content)
    if (absolute !== undefined) {
      return { kind: 'deny', reason: `Refusing to write ${filePath}: the content contains an absolute filesystem path (${absolute}). Use a path inside the project, or a placeholder such as <project>.` }
    }
    return next()
  })
}
